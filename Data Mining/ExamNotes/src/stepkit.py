# -*- coding: utf-8 -*-
"""Shared machinery for the step-by-step figures under every numerical.

Each chapter script (ch2fig.py .. ch7fig.py) defines its techniques and its
panels, recomputes every number from the problem data, asserts each one is
printed in its ch<N>-num.tex, and hands the figures to render() here.

The pattern is AI's ch2fig.py: one panel per step of the worked solution, a
coloured TECHNIQUE chip on every panel naming the move the step makes, the
decisive step framed as KEY STEP, and a generated index at the top of the
chapter listing every move and where it is used. The figures draw the
SOLUTION, never a source figure ([[exam-notes-style]]: never redraw).

A figure lands in the .tex at a line reading exactly
    % ch<N>fig:slot <name>
and is written between
    % ch<N>fig:<name> (generated by ch<N>fig.py; do not edit)
    ...
    % ch<N>fig:end
so a rerun replaces the old block instead of stacking a second one.
Figures are PNGs so tools/anki_from_notes.py carries them onto the cards.
"""
