class Techs(object):
    """A chapter's moves: key -> (chip label, meaning), in index order."""

    def __init__(self, items):
        self.order = [k for k, _, _ in items]
        self.label = {k: lab for k, lab, _ in items}
        self.what = {k: w for k, _, w in items}
        self.col = {k: "t%s" % re.sub(r"[^A-Za-z]", "", k) for k, _, _ in items}
        self.hex = {k: CHIP_HEX[i % len(CHIP_HEX)] for i, k in enumerate(self.order)}
        self.used = {k: [] for k in self.order}   # (figure short name, step, key?)

    def colours(self):
        return "".join(r"\definecolor{%s}{HTML}{%s}" % (self.col[k], self.hex[k])
                       for k in self.order)

    def chip(self, k, where, name):
        return r"\node[chip, fill=%s] (%s) at %s {%s};" % (self.col[k], name, where,
                                                            self.label[k])

    def index(self, fullwidth_cm=16.6):
        if len(self.order) > 20:
            return self.index2(fullwidth_cm)
        rows = []
        for k in self.order:
            where = []
            seen = {}
            for fig, step, key in self.used[k]:
                seen.setdefault(fig, []).append(
                    (r"\textbf{\color{mkc}%d}" % step) if key else str(step))
            for fig, steps in seen.items():
                where.append("%s %s" % (fig, ",".join(steps)))
            rows.append(r"\tikz[baseline=(c.base)]\node[chip, fill=%s, anchor=base] (c) {%s};"
                        r" & %s & \leavevmode{\color{sub}%s} \\"
                        % (self.col[k], self.label[k], self.what[k],
                           "; ".join(where) or "--"))
        w2 = 0.46 * fullwidth_cm
        w3 = fullwidth_cm - w2 - 3.0
        return (r"\begin{panelbox}\footnotesize\renewcommand{\arraystretch}{1.35}"
                r"\begin{tabular}{@{}l>{\raggedright\arraybackslash}p{%.1fcm}"
                r">{\raggedright\arraybackslash}p{%.1fcm}@{}}"
                r"\textbf{Move} & \textbf{What it says} & \textbf{Where it is used"
                r" (problem, step; {\color{mkc}orange} = the key step)} \\ \hline"
                % (w2, w3) + "\n" + "\n".join(rows) + r"\end{tabular}\end{panelbox}")


    def where(self, k):
        seen = {}
        for fig, step, key in self.used[k]:
            seen.setdefault(fig, []).append((r"\textbf{\color{mkc}%d}" % step) if key else str(step))
        return "; ".join("%s %s" % (f, ",".join(s)) for f, s in seen.items()) or "--"

    def index2(self, fullwidth_cm):
        """Two side-by-side tables: a long index would otherwise fill a page."""
        half = (fullwidth_cm - 0.6) / 2
        colw = half - 2.55
        body = []
        for k in self.order:
            body.append(r"\tikz[baseline=(c.base)]\node[chip, fill=%s, anchor=base] (c) {%s};"
                        r" & %s\newline{\color{sub}\scriptsize %s} \\"
                        % (self.col[k], self.label[k], self.what[k], self.where(k)))
        n = (len(body) + 1) // 2
        head = (r"\begin{tabular}[t]{@{}l>{\raggedright\arraybackslash}p{%.2fcm}@{}}"
                r"\textbf{Move} & \textbf{What it says} {\color{sub}\scriptsize(where: problem, step;"
                r" {\color{mkc}orange} = key step)} \\ \hline" % colw)
        tabs = [head + "\n" + "\n".join(part) + r"\end{tabular}" for part in (body[:n], body[n:])]
        return (r"\begin{panelbox}\scriptsize\renewcommand{\arraystretch}{1.2}"
                + tabs[0] + r"\hspace{0.6cm}" + tabs[1] + r"\end{panelbox}")


